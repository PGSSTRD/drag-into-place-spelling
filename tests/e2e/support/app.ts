interface LaunchOptions extends RuntimeOptions {
  fixture?: ContentFixture;
  content?: unknown;
  rawContent?: string;
  removeFiles?: string[];
  corruptFiles?: string[];
  files?: Record<string, string | Buffer>;
  missingFont?: boolean;
  reducedMotion?: "reduce" | "no-preference";
  clock?: boolean;
}

interface AppHarness {
  root: string;
  launch: (options?: LaunchOptions) => Promise<void>;
  url: string;
}

function confined(root: string, name: string): string {
  const file = resolve(root, name);
  const path = relative(root, file);
  if (!path || path === ".." || path.startsWith(`..${sep}`) || isAbsolute(path)) {
    throw new Error(`Fixture path outside staging: ${name}`);
  }
  return file;
}

async function writeAsset(root: string, name: string, data: string | Buffer): Promise<void> {
  const file = confined(root, name);
  await mkdir(resolve(file, ".."), { recursive: true });
  await writeFile(file, data);
}

async function stageContent(root: string, pack: ContentPack): Promise<void> {
  await rm(resolve(root, "lang"), { recursive: true, force: true });
  const wave = syntheticWave();
  const assets = new Map<string, { path: string; creator: string; license: string; source: string; notes: string }>();
  const original = JSON.parse(await readFile(resolve(root, "licenses.json"), "utf8")) as { assets: Array<{ path: string; creator: string; license: string; source: string; notes: string }> };
  for (const asset of original.assets.filter((asset) => !asset.path.startsWith("lang/"))) assets.set(asset.path, asset);
  for (const level of pack.levels) {
    await writeAsset(root, level.image_path,
      `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><circle cx="32" cy="32" r="24" fill="hsl(${level.level_id * 70} 70% 40%)"/></svg>`);
    for (const [index, audio] of [level.word_audio_path, ...level.letter_audio_paths].entries()) {
      await writeAsset(root, audio, syntheticWave(440 + level.level_id * 100 + index * 20));
    }
    for (const asset of [level.image_path, level.word_audio_path, ...level.letter_audio_paths]) {
      assets.set(asset, { path: asset, creator: "Project contributors", license: "CC0-1.0", source: "Generated by browser acceptance fixtures", notes: "Original synthetic fixture only; not production pronunciation or artwork." });
    }
  }
  await writeAsset(root, "assets/audios/incorrect.wav", wave);
  assets.set("assets/audios/incorrect.wav", { path: "assets/audios/incorrect.wav", creator: "Project contributors", license: "CC0-1.0", source: "Generated by browser acceptance fixtures", notes: "Original synthesized tone; no samples." });
  await writeAsset(root, "licenses.json", JSON.stringify({ assets: [...assets.values()] }, null, 2));
  await writeAsset(root, "FIXTURE-LICENSE.txt",
    "Synthetic SVG shapes and generated sine-wave PCM audio in this staging folder are original test fixtures dedicated to the public domain under CC0-1.0 (https://creativecommons.org/publicdomain/zero/1.0/). No third-party samples or recordings are used. Bundled Lexend remains OFL-1.1; see assets/fonts/OFL-Lexend.txt. Other copied production assets retain their licenses.json records. These fixtures do not prove pronunciation or production distribution approval.\n");
  await writeAsset(root, "lang/english/levels.json", JSON.stringify(pack, null, 2));
}

const mime: Record<string, string> = {
  ".html": "text/html", ".js": "text/javascript", ".css": "text/css",
  ".json": "application/json", ".svg": "image/svg+xml", ".wav": "audio/wav",
  ".mp3": "audio/mpeg", ".woff2": "font/woff2", ".txt": "text/plain",
};

async function serve(root: string): Promise<{ server: Server; origin: string; errors: string[] }> {
  const errors: string[] = [];
  const server = createServer((request, response) => {
    void (async () => {
      let file: string;
      try {
        const pathname = decodeURIComponent(new URL(request.url ?? "/", "http://localhost").pathname);
        file = confined(root, pathname === "/" ? "index.html" : `.${pathname}`);
      } catch {
        response.writeHead(400).end();
        return;
      }
      let data: Buffer;
      try {
        data = await readFile(file);
      } catch (error) {
        if (error instanceof Error && "code" in error && error.code === "ENOENT") {
          response.writeHead(404).end();
          return;
        }
        throw error;
      }
      response.setHeader("Content-Type", mime[extname(file)] ?? "application/octet-stream");
      response.setHeader("Cache-Control", "no-store");
      response.setHeader("Accept-Ranges", "bytes");
      const range = request.headers.range;
      if (range) {
        const match = /^bytes=(\d+)-(\d*)$/.exec(range);
        const start = match ? Number(match[1]) : -1;
        const end = match?.[2] ? Math.min(Number(match[2]), data.length - 1) : data.length - 1;
        if (start < 0 || start >= data.length || end < start) {
          response.writeHead(416, { "Content-Range": `bytes */${data.length}` }).end();
          return;
        }
        response.writeHead(206, { "Content-Range": `bytes ${start}-${end}/${data.length}`, "Content-Length": end - start + 1 });
        response.end(data.subarray(start, end + 1));
      } else {
        response.writeHead(200, { "Content-Length": data.length });
        response.end(data);
      }
    })().catch((error: unknown) => {
      errors.push(String(error));
      if (!response.headersSent) response.writeHead(500);
      response.end();
    });
  });
  await new Promise<void>((ready, reject) => {
    server.once("error", reject);
    server.listen(0, "127.0.0.1", ready);
  });
  const address = server.address();
  if (!address || typeof address === "string") throw new Error("HTTP fixture did not allocate a port");
  return { server, origin: `http://127.0.0.1:${address.port}`, errors };
}

export const test = base.extend<{ app: AppHarness }>({
  app: async ({ page, context }, use, testInfo) => {
    const root = await mkdtemp(resolve(tmpdir(), "drag-spelling-e2e-"));
    let endpoint: Awaited<ReturnType<typeof serve>> | undefined;
    const diagnostics: Array<{ type: string; message: string }> = [];
    const outbound: string[] = [];
    const runtimeNetwork: Array<{ api: string; url: string }> = [];
    let launched = false;
    try {
      await cp(resolve("dist"), root, { recursive: true });
      const transport = testInfo.project.metadata.transport;
      if (transport !== "http" && transport !== "file") throw new Error("Unknown browser transport");
      if (transport === "http") endpoint = await serve(root);
      const url = new URL(transport === "file" ? pathToFileURL(resolve(root, "index.html")).href : `${endpoint!.origin}/`);
      url.searchParams.set("cr_user_id", "browser-fixture");
      url.searchParams.set("cr_lang", "english");
      page.on("console", (message) => {
        if (message.text().startsWith("__browserHarnessNetwork ")) {
          const entry: unknown = JSON.parse(message.text().slice("__browserHarnessNetwork ".length));
          if (typeof entry !== "object" || entry === null || !("api" in entry) || !("url" in entry)
            || typeof entry.api !== "string" || typeof entry.url !== "string") {
            throw new Error("Invalid runtime network diagnostic");
          }
          runtimeNetwork.push({ api: entry.api, url: entry.url });
        }
        if (message.type() === "warning" || message.type() === "error") diagnostics.push({ type: message.type(), message: message.text() });
      });
      page.on("pageerror", (error) => diagnostics.push({ type: "pageerror", message: error.message }));
      await context.route("**/*", async (route) => {
        const request = new URL(route.request().url());
        if ((request.protocol === "http:" || request.protocol === "https:") && request.origin !== endpoint?.origin) {
          outbound.push(request.href);
          await route.abort("blockedbyclient");
        } else {
          await route.continue();
        }
      });
      await use({
        root,
        url: url.href,
        async launch(options = {}) {
          if (launched) throw new Error("Launch once per test; use page.reload() for reload checks");
          launched = true;
          const fixture = options.fixture ?? "F-01";
          if (fixture !== "F-11") await stageContent(root, structuredClone(contentFixtures[fixture]));
          if (options.content !== undefined) await writeAsset(root, "lang/english/levels.json", JSON.stringify(options.content));
          if (options.rawContent !== undefined) await writeAsset(root, "lang/english/levels.json", options.rawContent);
          for (const file of options.removeFiles ?? []) await rm(confined(root, file));
          for (const file of options.corruptFiles ?? []) await writeAsset(root, file, "corrupt fixture");
          for (const [file, data] of Object.entries(options.files ?? {})) await writeAsset(root, file, data);
          if (options.missingFont) {
            await rm(confined(root, "assets/fonts/lexend-v26-latin-regular.woff2"));
            const builtFonts = (await readdir(resolve(root, "assets"))).filter((file) => /^lexend-.*\.woff2$/.test(file));
            if (builtFonts.length === 0) throw new Error("No built Lexend font found for missing-font injection");
            for (const file of builtFonts) await rm(confined(root, `assets/${file}`));
          }
          await page.emulateMedia({ reducedMotion: options.reducedMotion ?? "no-preference" });
          await installRuntime(page, options);
          if (options.clock) {
            await page.clock.install({ time: new Date("2026-01-01T00:00:00Z") });
            await page.clock.pauseAt(new Date("2026-01-01T00:00:01Z"));
          }
          await page.goto(url.href);
        },
      });
      const externalAPIs = runtimeNetwork.filter(({ url: attempted }) => {
        const request = new URL(attempted);
        return !["file:", "data:", "blob:"].includes(request.protocol) && request.origin !== endpoint?.origin;
      });
      expect(outbound, "No outbound requests from isolated production test").toEqual([]);
      expect(externalAPIs, "No external runtime API attempts, even if blocked").toEqual([]);
      expect(endpoint?.errors ?? [], "Fixture HTTP server errors").toEqual([]);
      expect(diagnostics.filter(({ type }) => type === "pageerror"), "No uncaught application errors").toEqual([]);
    } finally {
      try {
        await testInfo.attach("harness-diagnostics", {
          body: JSON.stringify({ diagnostics, outbound, runtimeNetwork, serverErrors: endpoint?.errors ?? [] }, null, 2),
          contentType: "application/json",
        });
      } finally {
        try {
          if (endpoint) {
            endpoint.server.closeAllConnections();
            await new Promise<void>((done, reject) => endpoint!.server.close((error) => error ? reject(error) : done()));
          }
        } finally {
          await rm(root, { recursive: true, force: true });
        }
      }
    }
  },
});

export { expect };
